// Generates the typed client definitions used by the customer app from the contracts in
// generated/openapi/services/<service>.openapi.yaml into src/api/gen/:
//   customer-channel.d.ts   the customer channel BFF (/v1/me/*): every signed-in screen
//   customer.d.ts           dev-mode login only (customer search)
//   onboarding-public.d.ts  sign-up: only the public applicant surface of onboarding-service
//                           (/v1/onboarding/public/*, no bearer token; X-Applicant-Token), filtered from the full
//                           contract so the sign-up screens cannot call a staff onboarding endpoint by mistake
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const specs = join(root, "..", "..", "generated", "openapi", "services");
const out = (name) => join(root, "src", "api", "gen", `${name}.d.ts`);

/** Whole service contracts. */
export const SERVICES = ["customer-channel", "customer"];

/** Path subsets of a service contract: [output name, service, path prefix]. */
export const SUBSETS = [["onboarding-public", "onboarding", "/v1/onboarding/public/"]];

const bin = join(root, "node_modules", "openapi-typescript", "bin", "cli.js");
for (const s of SERVICES) {
  execFileSync(process.execPath, [bin, join(specs, `${s}-service.openapi.yaml`), "-o", out(s)], { stdio: "inherit" });
}

/** Keeps only the paths under `prefix` and the components they reference (transitively). */
function subset(spec, prefix) {
  const paths = Object.fromEntries(Object.entries(spec.paths ?? {}).filter(([p]) => p.startsWith(prefix)));
  if (Object.keys(paths).length === 0) throw new Error(`no paths under ${prefix}`);
  const keep = new Set();
  const queue = [paths];
  while (queue.length) {
    const node = queue.pop();
    if (Array.isArray(node)) { queue.push(...node); continue; }
    if (!node || typeof node !== "object") continue;
    for (const [k, v] of Object.entries(node)) {
      if (k === "$ref" && typeof v === "string" && v.startsWith("#/components/") && !keep.has(v)) {
        keep.add(v);
        const [, , section, name] = v.split("/");
        queue.push(spec.components?.[section]?.[name]);
      } else if (v && typeof v === "object") queue.push(v);
    }
  }
  const components = {};
  for (const ref of keep) {
    const [, , section, name] = ref.split("/");
    (components[section] ??= {})[name] = spec.components[section][name];
  }
  if (spec.components?.securitySchemes) components.securitySchemes = spec.components.securitySchemes;
  return { ...spec, paths, components, tags: undefined, webhooks: undefined };
}

for (const [name, service, prefix] of SUBSETS) {
  const spec = yaml.load(readFileSync(join(specs, `${service}-service.openapi.yaml`), "utf8"));
  const ast = await openapiTS(subset(spec, prefix));
  const header = "/**\n * This file was auto-generated by openapi-typescript (scripts/gen-api.mjs: "
    + `${service}-service paths under ${prefix}).\n * Do not make direct changes to the file.\n */\n\n`;
  writeFileSync(out(name), header + astToString(ast));
  console.log(`${name}: ${Object.keys(spec.paths).filter((p) => p.startsWith(prefix)).length} paths -> ${out(name)}`);
}
