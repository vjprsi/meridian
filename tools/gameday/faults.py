def run(cmd: str, execute: bool, docker: bool = False) -> None:
    full = shlex.split(DOCKER) + [cmd] if docker else cmd
    shown = cmd if not docker else f"{DOCKER} '{cmd}'"
    print(f"  $ {shown}")
    if execute:
        r = subprocess.run(full, shell=not docker, capture_output=True, text=True)
        out = (r.stdout + r.stderr).replace("\0", "").strip()
        if out:
            print("    " + out.replace("\n", "\n    "))


def explain(fault: str) -> None:
    f = FAULTS.get(fault)
    if not f:
        return
    print("expected alerts:")
    for a in f["expected"]:
        print(f"  - {a}")
    print(f"watch: {f['watch']}")
    print(f"T0 = {time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())} (record it in the game-day log)")


def http(method: str, url: str, body=None) -> tuple[int, object]:
    h = {"Accept": "application/json", "X-Meridian-Service": "platform-ops", "X-User": "platform-ops",
         "Content-Type": "application/json", "Idempotency-Key": str(uuid.uuid4())}
    if os.environ.get("MERIDIAN_OPERATOR_TENANT"):
        h["X-Tenant-Id"] = os.environ["MERIDIAN_OPERATOR_TENANT"]
    if os.environ.get("MERIDIAN_OPS_TOKEN"):
        h["Authorization"] = "Bearer " + os.environ["MERIDIAN_OPS_TOKEN"]
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(url, data=data, method=method, headers=h)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            raw = r.read()
            return r.status, json.loads(raw) if raw else None
    except urllib.error.HTTPError as e:
        raw = e.read()
        try:
            return e.code, json.loads(raw)
        except ValueError:
            return e.code, raw.decode(errors="replace")
    except (urllib.error.URLError, OSError) as e:
        return 0, str(e)


def service_url(a, name: str) -> str:
    port = MANIFEST[name]["port"]
    return (a.url_template or "http://localhost:{port}").replace("{name}", name).replace("{port}", str(port))


def selected(a) -> list[str]:
    if a.services:
        return [s.strip() for s in a.services.split(",") if s.strip()]
    return sorted(MANIFEST)


# ---------------------------------------------------------------------------------------------------- faults

def kill_service(a) -> None:
    print(f"fault: kill {a.service}")
    if a.cloud:
        run(f"kubectl -n {a.namespace} delete pod -l app.kubernetes.io/name={a.service} --wait=false", a.execute)
        print("  (all replicas at once; for a single replica add --field-selector or delete one pod by name)")
    else:
        pid_file = ROOT / ".run" / f"{a.service}.pid"
        pid = pid_file.read_text().strip() if pid_file.exists() else "<pid from .run/>"
        run(f"taskkill /PID {pid} /T /F" if os.name == "nt" else f"kill -9 {pid}", a.execute)
        print(f"  restart: python tools/dev.py up {a.service}")
    explain("kill-service")


def db_outage(a) -> None:
    print(f"fault: database outage for {a.seconds} s (local: every service database at once)")
    run("docker stop meridian-postgres", a.execute, docker=True)
    if a.execute:
        time.sleep(a.seconds)
    run("docker start meridian-postgres", a.execute, docker=True)
    explain("db-outage")


def db_failover(a) -> None:
    print("fault: Aurora writer failover to a reader in another AZ (cloud) - AZ loss simulation")
    if not a.cloud:
        print("  local stack has a single PostgreSQL: use db-outage instead")
    run(f"aws rds failover-db-cluster --db-cluster-identifier {a.cluster}", a.execute and a.cloud)
    print("  AZ-wide alternative (AWS FIS): action aws:rds:failover-db-cluster + aws:network:disrupt-connectivity "
          "scope=availability-zone on the cell's subnets")
    explain("db-failover")


def region_failover(a) -> None:
    print("fault: unplanned regional failover (Aurora Global) - run with the router steps of MULTI_REGION section 5")
    flag = "" if a.planned else " --allow-data-loss"
    verb = "switchover-global-cluster" if a.planned else "failover-global-cluster"
    run(f"aws rds {verb} --global-cluster-identifier {a.global_cluster} --target-db-cluster-identifier "
        f"{a.target_arn}{flag}", a.execute and a.cloud)
    print("  then: faults.py cell-offline --cell <primary>; faults.py cell-online --cell <standby> (services promote "
          "themselves); faults.py cell-role to watch; rpo_probe.py check")
    print("  network-level region loss (AWS FIS): aws:network:disrupt-connectivity on the primary cell's subnets, or a "
          "security-group deny on the gateways and the database")
    explain("region-failover")


def kafka_loss(a) -> None:
    print(f"fault: Kafka unavailable for {a.seconds} s (local single broker = whole cluster)")
    run("docker stop meridian-kafka", a.execute, docker=True)
    if a.execute:
        time.sleep(a.seconds)
    run("docker start meridian-kafka", a.execute, docker=True)
    explain("kafka-loss")


def kafka_broker(a) -> None:
    print(f"fault: MSK broker {a.broker} reboot (one of three; RF 3, min.insync.replicas 2)")
    run(f"aws kafka reboot-broker --cluster-arn {a.cluster_arn} --broker-ids {a.broker}", a.execute and a.cloud)
    explain("kafka-broker")


def cell_status(a, action: str) -> None:
    url = f"{a.registry}/v1/platform/cells/{a.cell}/{action}"
    print(f"registry: POST {url}")
    body = {"reason": a.reason}
    if a.execute:
        status, resp = http("POST", url, body)
        print(f"  -> HTTP {status} {json.dumps(resp)[:400]}")
    explain(f"cell-{action}")


def promote_cell(a) -> None:
    print(f"promote (cell-role) on {len(selected(a))} services - normally not needed: services promote themselves "
          f"when the registry shows the cell ACTIVE")
    for name in selected(a):
        url = service_url(a, name) + "/v1/internal/ops/cell-role/promote"
        if not a.execute:
            print(f"  POST {url}")
            continue
        status, resp = http("POST", url, {"reason": a.reason})
        state = resp.get("promotion_state") if isinstance(resp, dict) else resp
        print(f"  {name:34} HTTP {status} {state}")


def cell_role(a) -> None:
    for name in selected(a):
        status, resp = http("GET", service_url(a, name) + "/v1/internal/ops/cell-role")
        if isinstance(resp, dict) and status == 200:
            print(f"  {name:34} {resp.get('role'):8} {resp.get('promotion_state', '-'):22} "
                  f"relay_paused={resp.get('relay_paused')} held={len(resp.get('held_listeners', []))} "
                  f"{resp.get('promotion_detail', '')}")
        else:
            print(f"  {name:34} HTTP {status} {str(resp)[:120]}")


def outbox_replay(a) -> None:
    body = {"from": a.from_, "to": a.to, "basis": a.basis, "reason": a.reason, "dry_run": a.dry_run}
    if a.types:
        body["event_types"] = [t.strip() for t in a.types.split(",")]
    if a.tenant:
        body["tenant_id"] = a.tenant
    for name in selected(a):
        url = service_url(a, name) + "/v1/internal/ops/outbox/replay"
        if not a.execute:
            print(f"  POST {url} {json.dumps(body)}")
            continue
        status, resp = http("POST", url, body)
        if isinstance(resp, dict) and status == 200:
            print(f"  {name:34} matched={resp.get('matched')} published={resp.get('published')} "
                  f"{resp.get('replay_id')}{' (dry run)' if resp.get('dry_run') else ''}")
        else:
            print(f"  {name:34} HTTP {status} {str(resp)[:160]}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")

    def common(s):
        s.add_argument("--execute", action="store_true", help="run it (default: print only)")
        s.add_argument("--cloud", action="store_true", help="cloud form (kubectl / aws) instead of the local stack")
        return s

    s = common(sub.add_parser("kill-service"))
    s.add_argument("service")
    s.add_argument("--namespace", default="meridian")
    for name in ("db-outage", "kafka-loss"):
        common(sub.add_parser(name)).add_argument("--seconds", type=int, default=60)
    common(sub.add_parser("db-failover")).add_argument("--cluster", default="<cell aurora cluster id>")
    s = common(sub.add_parser("region-failover"))
    s.add_argument("--global-cluster", default="<global cluster id>")
    s.add_argument("--target-arn", default="<standby cluster arn>")
    s.add_argument("--planned", action="store_true", help="switchover (RPO 0) instead of failover --allow-data-loss")
    s = common(sub.add_parser("kafka-broker"))
    s.add_argument("--cluster-arn", default="<msk cluster arn>")
    s.add_argument("--broker", default="1")
    for name in ("cell-offline", "cell-online"):
        s = common(sub.add_parser(name))
        s.add_argument("--cell", required=True)
        s.add_argument("--registry", default="http://localhost:9124")
        s.add_argument("--reason", default="game day")
    for name in ("promote-cell", "cell-role", "outbox-replay"):
        s = common(sub.add_parser(name))
        s.add_argument("--services", help="comma separated (default: every service of the manifest)")
        s.add_argument("--url-template", help="e.g. http://{name}.meridian.svc.cluster.local (default localhost:<port>)")
        s.add_argument("--reason", default="game day")
        if name == "outbox-replay":
            s.add_argument("--from", dest="from_", required=True)
            s.add_argument("--to", required=True)
            s.add_argument("--basis", default="CREATED", choices=["CREATED", "PUBLISHED"])
            s.add_argument("--types")
            s.add_argument("--tenant")
            s.add_argument("--dry-run", action="store_true")
    a = p.parse_args()
    if a.cmd == "list":
        for k, v in FAULTS.items():
            print(f"{k:16} {v['watch'][:100]}")
        return
    handlers = {"kill-service": kill_service, "db-outage": db_outage, "db-failover": db_failover,
                "region-failover": region_failover, "kafka-loss": kafka_loss, "kafka-broker": kafka_broker,
                "cell-offline": lambda x: cell_status(x, "offline"), "cell-online": lambda x: cell_status(x, "online"),
                "promote-cell": promote_cell, "cell-role": cell_role, "outbox-replay": outbox_replay}
    handlers[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
