#!/usr/bin/env python3
"""Meridian editions resolver (WE-PKG-1 / D-ED-01).

One codebase, two commercial editions. Reads the declarative manifest (spec/editions.yaml) and the generated Helm
base values (infra/helm/meridian/values.yaml), and writes, per edition:

  generated/editions/<code>.json      resolved per-service enablement + metadata (ops/docs/tooling)
  deploy/editions/values-<code>.yaml   a complete Helm values file with `enabled` flipped per service + global.edition

Enablement: a service is ON when its domain is in core_domains or the edition's enabled_domains; otherwise OFF.
Services without a domain (e.g. the edge gateway) keep the base `enabled`. Run after tools/generate.py and
tools/helm_chart.py.

Usage: python tools/editions.py [--check]
  --check  fail (exit 1) if any output is missing or stale instead of writing (for CI).
"""
from __future__ import annotations

import copy
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "editions.yaml"
BASE_VALUES = ROOT / "infra" / "helm" / "meridian" / "values.yaml"
GEN = ROOT / "generated" / "editions"
DEPLOY = ROOT / "deploy" / "editions"

_GENERATED = "# GENERATED by tools/editions.py from spec/editions.yaml — do not edit by hand.\n"


def resolve(spec: dict, base: dict) -> dict:
    """code -> (profile dict, complete values dict)."""
    core = set(spec.get("core_domains", []))
    out = {}
    for code, ed in spec.get("editions", {}).items():
        enabled_domains = core | set(ed.get("enabled_domains", []))
        optional_domains = set(ed.get("optional_domains", []))
        values = copy.deepcopy(base)
        services = {}
        for svc in values.get("services", []):
            dom = svc.get("domain")
            if dom is None:
                on = bool(svc.get("enabled", True))  # infra (edge gateway): keep base
            else:
                on = dom in enabled_domains
            svc["enabled"] = on
            services[svc["name"]] = {"domain": dom, "enabled": on, "optional": dom in optional_domains}
        values.setdefault("global", {})["edition"] = code
        profile = {
            "code": code,
            "name": ed.get("name"),
            "tagline": ed.get("tagline"),
            "tenant_types": ed.get("tenant_types", []),
            "description": (ed.get("description") or "").strip(),
            "starter_pack": ed.get("starter_pack"),
            "channels": ed.get("channels", []),
            "enabled_domains": sorted(enabled_domains),
            "optional_domains": sorted(optional_domains),
            "enabled_count": sum(1 for s in services.values() if s["enabled"]),
            "disabled_count": sum(1 for s in services.values() if not s["enabled"]),
            "services": dict(sorted(services.items())),
        }
        out[code] = (profile, values)
    return out


def render(profile: dict, values: dict) -> tuple[str, str]:
    profile_text = json.dumps(profile, indent=2, ensure_ascii=False) + "\n"
    values_text = _GENERATED + yaml.safe_dump(values, sort_keys=False, allow_unicode=True, width=120)
    return profile_text, values_text


def main() -> int:
    check = "--check" in sys.argv[1:]
    if not BASE_VALUES.exists():
        print(f"error: {BASE_VALUES} not found — run tools/helm_chart.py first", file=sys.stderr)
        return 1
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    base = yaml.safe_load(BASE_VALUES.read_text(encoding="utf-8"))
    resolved = resolve(spec, base)

    GEN.mkdir(parents=True, exist_ok=True)
    DEPLOY.mkdir(parents=True, exist_ok=True)
    stale = []
    summary = []
    for code, (profile, values) in resolved.items():
        profile_text, values_text = render(profile, values)
        pj = GEN / f"{code}.json"
        vv = DEPLOY / f"values-{code}.yaml"
        if check:
            if not pj.exists() or pj.read_text(encoding="utf-8") != profile_text:
                stale.append(str(pj))
            if not vv.exists() or vv.read_text(encoding="utf-8") != values_text:
                stale.append(str(vv))
        else:
            pj.write_text(profile_text, encoding="utf-8")
            vv.write_text(values_text, encoding="utf-8")
        summary.append(f"{code}: {profile['enabled_count']} enabled / {profile['disabled_count']} disabled "
                       f"(starter pack: {profile['starter_pack']})")

    if check and stale:
        print("editions outputs are stale; run python tools/editions.py:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    print("editions " + ("check OK" if check else "written") + ": " + "; ".join(summary))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
