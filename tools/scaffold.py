#!/usr/bin/env python3
"""Scaffolds the Gradle monorepo from generated/services.json (run tools/generate.py first).

Always regenerated:   settings.gradle.kts, docs/SERVICES.md
Created only if absent (safe to re-run; hand-written code is never overwritten):
  services/<name>/build.gradle.kts
  services/<name>/src/main/java/<pkg>/<Name>Application.java
  services/<name>/src/main/resources/application.yml
  services/<name>/src/main/java/<pkg>/api/<Tag>Controller.java   (implements generated <Tag>Api; 501 until done)
  services/<name>/src/test/java/<pkg>/<Name>ApplicationTests.java

Usage: python tools/scaffold.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "generated" / "services.json"


def pascal(s: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", s) if w)


def write_if_absent(path: Path, content: str) -> bool:
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def main():
    services = json.loads(MANIFEST.read_text(encoding="utf-8"))
    created = 0

    libs = sorted(p.name for p in (ROOT / "libs").iterdir() if (p / "build.gradle.kts").exists())
    settings = ["// Generated by tools/scaffold.py. DO NOT EDIT.",
                'rootProject.name = "meridian-core"',
                "",
                'pluginManagement { includeBuild("build-logic") }',
                "",
                "dependencyResolutionManagement {",
                "    repositories { mavenCentral() }",
                "}",
                ""]
    settings += [f'include(":libs:{name}")' for name in libs]
    platform = sorted(p.name for p in (ROOT / "platform").iterdir() if (p / "build.gradle.kts").exists())         if (ROOT / "platform").exists() else []
    settings += [""] + [f'include(":platform:{name}")' for name in platform]
    settings += [""]
    settings += [f'include(":services:{s["name"]}")' for s in sorted(services, key=lambda x: x["name"])]
    (ROOT / "settings.gradle.kts").write_text("\n".join(settings) + "\n", encoding="utf-8", newline="\n")

    for s in services:
        name, pkg = s["name"], s["package"]
        base = ROOT / "services" / name
        jdir = base / "src" / "main" / "java" / Path(*pkg.split("."))
        app = pascal(name.removesuffix("-service")) + "Application"

        created += write_if_absent(base / "build.gradle.kts", f'''plugins {{ id("meridian.spring-service") }}

meridianService {{
    basePackage = "{pkg}"
    database = "{s["database"]}"
}}
''')

        created += write_if_absent(jdir / f"{app}.java", f'''package {pkg};

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;

/** {s["name"]}: {s["description"][:180]} */
@SpringBootApplication
public class {app} {{
    public static void main(String[] args) {{
        SpringApplication.run({app}.class, args);
    }}
}}
''')

        created += write_if_absent(base / "src" / "main" / "resources" / "application.yml", f'''# {name} ({s["domain_title"]}). Defaults target the local stack in infra/local; override with env vars in
# other environments (e.g. SPRING_DATASOURCE_URL). Security mode is jwt unless MERIDIAN_SECURITY_MODE=dev.
server:
  port: {s["port"]}
  shutdown: graceful

spring:
  application:
    name: {name}
  threads:
    virtual:
      enabled: true
  datasource:
    url: jdbc:postgresql://localhost:15432/{s["database"]}?currentSchema={s["schema"]}
    username: meridian_app
    password: meridian_app
    hikari:
      maximum-pool-size: 20
  flyway:
    user: meridian
    password: meridian
    schemas: {s["schema"]}
    default-schema: {s["schema"]}
  kafka:
    bootstrap-servers: localhost:19092
    producer:
      acks: all
      properties:
        enable.idempotence: true
  security:
    oauth2:
      resourceserver:
        jwt:
          issuer-uri: http://localhost:15180/realms/meridian

meridian:
  security-mode: jwt          # jwt = OAuth2 tokens (default, every environment); dev = X-Tenant-Id headers, only when set
                              # explicitly (tools/dev.py and tests: MERIDIAN_SECURITY_MODE=dev); SEC-13
  events:
    topic: meridian.{s["domain"]}.v1

management:
  endpoints:
    web:
      exposure:
        include: health,info,metrics,prometheus
  endpoint:
    health:
      probes:
        enabled: true
  opentelemetry:
    resource-attributes:
      service.name: {name}
  otlp:
    metrics:
      export:
        url: http://localhost:14318/v1/metrics
  tracing:
    sampling:
      probability: 1.0
''')

        for tag in s["tags"]:
            cls = pascal(tag)
            created += write_if_absent(jdir / "api" / f"{cls}Controller.java", f'''package {pkg}.api;

import {pkg}.api.generated.{cls}Api;
import org.springframework.web.bind.annotation.RestController;

/**
 * {tag} API. Operations not yet overridden here return 501 Not Implemented (generated default methods).
 * Contract: generated/openapi/services/{name}.openapi.yaml
 */
@RestController
public class {cls}Controller implements {cls}Api {{
}}
''')

        tdir = base / "src" / "test" / "java" / Path(*pkg.split("."))
        created += write_if_absent(tdir / f"{app}Tests.java", f'''package {pkg};

import io.meridian.test.MeridianTestContainers;
import org.junit.jupiter.api.Test;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.annotation.Import;

/** Boots the service against real PostgreSQL 18 and Kafka; Flyway applies the generated schema. */
@SpringBootTest(properties = "meridian.events.relay-enabled=false")
@Import(MeridianTestContainers.class)
class {app}Tests {{

    @Test
    void contextLoadsAndSchemaMigrates() {{
    }}
}}
''')

    lines = ["# Services", "", "Generated by `tools/scaffold.py` from `generated/services.json`.", "",
             "| Service | Domain | Phase | Port | Database | Package | API groups |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    for s in sorted(services, key=lambda x: x["port"]):
        lines.append(f"| {s['name']} | {s['domain_title']} | {s['phase']} | {s['port']} | {s['database']} | "
                     f"`{s['package']}` | {len(s['tags'])} |")
    (ROOT / "docs" / "SERVICES.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"services={len(services)} libs={len(libs)} files_created={created}")


if __name__ == "__main__":
    main()
