package io.meridian.web.lifecycle;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import org.springframework.core.io.ClassPathResource;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Personal data of the platform's tables as declared by the spec: columns marked {@code pii}, how each row is linked to
 * a customer (data subject) and which columns never leave the service. Generated by {@code tools/generate.py} into the
 * service manifest ({@code generated/services.json}, {@code personal_data} of each service) and shipped on every
 * service's classpath as {@code meridian/services.json}.
 *
 * <p>Used by the data-lifecycle endpoints (archive, purge, DSAR export and erasure, GAP-08) and by audit-service's
 * masking of event payloads (GAP-07).
 */
public final class PersonalDataCatalog {
    /** Manifest location on the classpath. */
    public static final String MANIFEST = "meridian/services.json";

    /**
     * One way a row reaches its customer: {@code column} holds the customer id; with {@code typeColumn} only where
     * {@code typeColumn = typeValue} (polymorphic owner); with {@code parent} the column is a foreign key to a row of
     * {@code parent}, itself linked.
     */
    public record SubjectPath(String column, String typeColumn, String typeValue, String parent) {}

    /** Personal-data facts of one table. */
    public record TableInfo(String table, List<String> pii, List<SubjectPath> subject, List<String> hidden,
                            boolean immutable) {
        public boolean linked() {
            return !subject.isEmpty();
        }
    }

    private final Map<String, TableInfo> tables;

    private PersonalDataCatalog(Map<String, TableInfo> tables) {
        this.tables = Collections.unmodifiableMap(tables);
    }

    /** The catalog of {@code service} from the manifest on the classpath (empty when the manifest is absent). */
    public static PersonalDataCatalog forService(JsonMapper json, String service) {
        JsonNode manifest = manifest(json);
        for (JsonNode s : manifest) {
            if (service.equals(s.path("name").asString())) {
                return new PersonalDataCatalog(parse(s.path("personal_data")));
            }
        }
        return new PersonalDataCatalog(Map.of());
    }

    /** Built from a {@code personal_data} object (tests). */
    public static PersonalDataCatalog of(JsonNode personalData) {
        return new PersonalDataCatalog(parse(personalData));
    }

    /** Every table of every service -> its pii columns (audit masking of event payloads). */
    public static Map<String, Set<String>> piiColumnsByTable(JsonMapper json) {
        Map<String, Set<String>> out = new LinkedHashMap<>();
        for (JsonNode s : manifest(json)) {
            s.path("personal_data").properties().forEach(e -> {
                Set<String> cols = new LinkedHashSet<>();
                e.getValue().path("pii").forEach(c -> cols.add(c.asString()));
                if (!cols.isEmpty()) {
                    out.computeIfAbsent(e.getKey(), k -> new LinkedHashSet<>()).addAll(cols);
                }
            });
        }
        return out;
    }

    public Map<String, TableInfo> tables() {
        return tables;
    }

    public Optional<TableInfo> table(String name) {
        return Optional.ofNullable(tables.get(name));
    }

    /** Tables that hold personal data of a customer (pii columns and a subject link). */
    public List<TableInfo> subjectTables() {
        return tables.values().stream().filter(TableInfo::linked).toList();
    }

    private static Map<String, TableInfo> parse(JsonNode pd) {
        Map<String, TableInfo> out = new LinkedHashMap<>();
        if (pd == null || !pd.isObject()) {
            return out;
        }
        pd.properties().forEach(e -> {
            JsonNode t = e.getValue();
            List<SubjectPath> paths = new ArrayList<>();
            t.path("subject").forEach(p -> paths.add(new SubjectPath(p.path("column").asString(),
                    p.path("type_column").asString(null), p.path("type_value").asString(null), p.path("parent").asString(null))));
            out.put(e.getKey(), new TableInfo(e.getKey(), strings(t.path("pii")), List.copyOf(paths),
                    strings(t.path("hidden")), t.path("immutable").asBoolean(false)));
        });
        return out;
    }

    private static List<String> strings(JsonNode arr) {
        List<String> out = new ArrayList<>();
        arr.forEach(x -> out.add(x.asString()));
        return List.copyOf(out);
    }

    private static JsonNode manifest(JsonMapper json) {
        ClassPathResource res = new ClassPathResource(MANIFEST);
        if (!res.exists()) {
            return json.createArrayNode();
        }
        try (InputStream in = res.getInputStream()) {
            return json.readTree(in);
        } catch (IOException e) {
            throw new UncheckedIOException("cannot read " + MANIFEST, e);
        }
    }
}
