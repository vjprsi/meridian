package io.meridian.fraud.ml;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

/**
 * Minimal, deterministic trainers producing {@code meridian-fraud-model/1} artefacts from {@link SyntheticFraudData}:
 * a standardised L2 logistic regression (batch gradient descent) and a gradient-boosted tree ensemble (logistic loss,
 * Newton leaves, exact greedy splits over quantile candidates, missing values to the "yes" branch) written in the
 * XGBoost JSON-dump structure. A stand-in for offline training (see docs/ML_FRAUD_TRAINING.md), not a library.
 */
public final class SampleModelTrainer {
    static final String NOTE = "SYNTHETIC: trained on data generated by SyntheticFraudData (seed " + SyntheticFraudData.SEED
            + "); for tests and demonstrations only, never for real decisions";

    private SampleModelTrainer() {}

    // ------------------------------------------------------------------ logistic regression

    public static ObjectNode logistic(List<SyntheticFraudData.Row> train, List<SyntheticFraudData.Row> holdout, JsonMapper json) {
        int d = SyntheticFraudData.FEATURES.size();
        double[] mean = new double[d];
        double[] std = new double[d];
        double[][] x = impute(train, d);
        for (int j = 0; j < d; j++) {
            double s = 0;
            for (double[] r : x) {
                s += r[j];
            }
            mean[j] = s / x.length;
            double v = 0;
            for (double[] r : x) {
                v += (r[j] - mean[j]) * (r[j] - mean[j]);
            }
            std[j] = Math.max(Math.sqrt(v / x.length), 1e-6);
        }
        for (int j = 0; j < d; j++) {
            mean[j] = round6(mean[j]);
            std[j] = round6(std[j]);
        }
        double[] w = new double[d];
        double b = 0;
        double lr = 0.5;
        double l2 = 1e-3;
        for (int it = 0; it < 400; it++) {
            double[] g = new double[d];
            double gb = 0;
            for (int i = 0; i < x.length; i++) {
                double m = b;
                for (int j = 0; j < d; j++) {
                    m += w[j] * (x[i][j] - mean[j]) / std[j];
                }
                double err = sigmoid(m) - train.get(i).label();
                gb += err;
                for (int j = 0; j < d; j++) {
                    g[j] += err * (x[i][j] - mean[j]) / std[j];
                }
            }
            b -= lr * gb / x.length;
            for (int j = 0; j < d; j++) {
                w[j] -= lr * (g[j] / x.length + l2 * w[j]);
            }
        }
        ObjectNode a = header(json, "LOGISTIC_REGRESSION", "sample-fraud-lr", "1.0.0-synthetic");
        ObjectNode l = a.putObject("logistic");
        l.put("intercept", round6(b));
        ArrayNode cw = l.putArray("coefficients");
        for (double v : w) {
            cw.add(round6(v));
        }
        ObjectNode st = l.putObject("standardize");
        ArrayNode ma = st.putArray("mean");
        ArrayNode sa = st.putArray("std");
        for (int j = 0; j < d; j++) {
            ma.add(mean[j]);
            sa.add(std[j]);
        }
        // missing beneficiary age: imputed with the training mean (contributes 0)
        a.putObject("missing_values").put("beneficiary_age_days", mean[SyntheticFraudData.FEATURES.indexOf("beneficiary_age_days")]);
        return a;
    }

    private static double[][] impute(List<SyntheticFraudData.Row> rows, int d) {
        int ba = SyntheticFraudData.FEATURES.indexOf("beneficiary_age_days");
        double s = 0;
        int n = 0;
        for (SyntheticFraudData.Row r : rows) {
            if (!Double.isNaN(r.x()[ba])) {
                s += r.x()[ba];
                n++;
            }
        }
        double fill = n == 0 ? 0 : s / n;
        double[][] x = new double[rows.size()][];
        for (int i = 0; i < rows.size(); i++) {
            x[i] = rows.get(i).x().clone();
            if (Double.isNaN(x[i][ba])) {
                x[i][ba] = fill;
            }
        }
        return x;
    }

    // ------------------------------------------------------------------ gradient-boosted trees

    public static ObjectNode trees(List<SyntheticFraudData.Row> train, int rounds, int depth, double eta, JsonMapper json) {
        int n = train.size();
        int d = SyntheticFraudData.FEATURES.size();
        double prior = train.stream().mapToInt(SyntheticFraudData.Row::label).average().orElse(0.5);
        double base = round6(StrictMath.log(prior / (1 - prior)));
        double[] margin = new double[n];
        Arrays.fill(margin, base);
        double[][] candidates = candidates(train, d, 16);
        ObjectNode a = header(json, "TREE_ENSEMBLE", "sample-fraud-gbdt", "1.0.0-synthetic");
        a.put("base_score", base);
        a.put("decision_type", "<");
        ArrayNode trees = a.putArray("trees");
        for (int t = 0; t < rounds; t++) {
            double[] g = new double[n];
            double[] h = new double[n];
            for (int i = 0; i < n; i++) {
                double p = sigmoid(margin[i]);
                g[i] = p - train.get(i).label();
                h[i] = Math.max(p * (1 - p), 1e-6);
            }
            int[] all = new int[n];
            for (int i = 0; i < n; i++) {
                all[i] = i;
            }
            int[] counter = {0};
            ObjectNode tree = grow(train, all, g, h, candidates, depth, 0, eta, counter, json);
            trees.add(tree);
            for (int i = 0; i < n; i++) {
                margin[i] += leaf(tree, train.get(i).x());
            }
        }
        return a;
    }

    private static ObjectNode grow(List<SyntheticFraudData.Row> rows, int[] idx, double[] g, double[] h, double[][] cand,
                                   int maxDepth, int depth, double eta, int[] counter, JsonMapper json) {
        double lambda = 1.0;
        double gs = 0;
        double hs = 0;
        for (int i : idx) {
            gs += g[i];
            hs += h[i];
        }
        ObjectNode node = json.createObjectNode();
        node.put("nodeid", counter[0]++);
        if (depth == maxDepth || idx.length < 20) {
            node.put("leaf", round6(-gs / (hs + lambda) * eta));
            node.put("cover", round6(hs));
            return node;
        }
        double best = 0;
        int bf = -1;
        double bt = 0;
        double parent = gs * gs / (hs + lambda);
        for (int f = 0; f < cand.length; f++) {
            for (double thr : cand[f]) {
                double gl = 0;
                double hl = 0;
                for (int i : idx) {
                    double v = rows.get(i).x()[f];
                    if (Double.isNaN(v) || v < thr) {
                        gl += g[i];
                        hl += h[i];
                    }
                }
                double gr = gs - gl;
                double hr = hs - hl;
                if (hl < 1.0 || hr < 1.0) {
                    continue;
                }
                double gain = gl * gl / (hl + lambda) + gr * gr / (hr + lambda) - parent;
                if (gain > best + 1e-9) {
                    best = gain;
                    bf = f;
                    bt = thr;
                }
            }
        }
        if (bf < 0) {
            node.put("leaf", round6(-gs / (hs + lambda) * eta));
            node.put("cover", round6(hs));
            return node;
        }
        List<Integer> l = new ArrayList<>();
        List<Integer> r = new ArrayList<>();
        for (int i : idx) {
            double v = rows.get(i).x()[bf];
            (Double.isNaN(v) || v < bt ? l : r).add(i);
        }
        node.put("depth", depth);
        node.put("split", SyntheticFraudData.FEATURES.get(bf));
        node.put("split_condition", bt);
        ObjectNode yes = grow(rows, l.stream().mapToInt(Integer::intValue).toArray(), g, h, cand, maxDepth, depth + 1, eta, counter, json);
        ObjectNode no = grow(rows, r.stream().mapToInt(Integer::intValue).toArray(), g, h, cand, maxDepth, depth + 1, eta, counter, json);
        node.put("yes", yes.get("nodeid").asInt());
        node.put("no", no.get("nodeid").asInt());
        node.put("missing", yes.get("nodeid").asInt());
        node.put("cover", round6(hs));
        node.putArray("children").add(yes).add(no);
        return node;
    }

    private static double leaf(ObjectNode node, double[] x) {
        ObjectNode n = node;
        while (!n.has("leaf")) {
            int f = SyntheticFraudData.FEATURES.indexOf(n.get("split").asString());
            double v = x[f];
            boolean yes = Double.isNaN(v) || v < n.get("split_condition").asDouble();
            n = (ObjectNode) n.get("children").get(yes ? 0 : 1);
        }
        return n.get("leaf").asDouble();
    }

    private static double[][] candidates(List<SyntheticFraudData.Row> rows, int d, int q) {
        double[][] out = new double[d][];
        for (int f = 0; f < d; f++) {
            int ff = f;
            double[] v = rows.stream().mapToDouble(r -> r.x()[ff]).filter(x -> !Double.isNaN(x)).sorted().toArray();
            java.util.TreeSet<Double> cuts = new java.util.TreeSet<>();
            for (int k = 1; k < q; k++) {
                double c = v[(int) ((long) k * (v.length - 1) / q)];
                // split between distinct values: "x < c" with c strictly above the lower values
                cuts.add(round6(c + 1e-6));
            }
            out[f] = cuts.stream().mapToDouble(Double::doubleValue).toArray();
        }
        return out;
    }

    // ------------------------------------------------------------------ shared

    private static ObjectNode header(JsonMapper json, String algorithm, String name, String version) {
        ObjectNode a = json.createObjectNode();
        a.put("format", "meridian-fraud-model/1");
        a.put("algorithm", algorithm);
        a.put("name", name);
        a.put("version", version);
        ArrayNode f = a.putArray("features");
        SyntheticFraudData.FEATURES.forEach(f::add);
        ObjectNode reasons = a.putObject("reason_codes");
        Map<String, String[]> rc = reasonCodes();
        rc.forEach((k, v) -> reasons.putObject(k).put("code", v[0]).put("description", v[1]));
        a.put("reason_min_contribution", 0.25);
        ObjectNode th = a.putObject("thresholds");
        th.putObject("default").put("step_up", 450).put("review", 650).put("block", 850);
        th.putObject("channels").putObject("ECOMMERCE").put("step_up", 400).put("review", 600).put("block", 800);
        ObjectNode meta = a.putObject("metadata");
        meta.put("synthetic", true);
        meta.put("note", NOTE);
        meta.put("seed", SyntheticFraudData.SEED);
        return a;
    }

    static Map<String, String[]> reasonCodes() {
        Map<String, String[]> m = new LinkedHashMap<>();
        m.put("customer_txn_count_1h", new String[] {"ML_HIGH_VELOCITY_1H", "Many transactions by the customer in the last hour"});
        m.put("customer_txn_count_24h", new String[] {"ML_HIGH_VELOCITY_24H", "Many transactions by the customer in the last 24 hours"});
        m.put("customer_txn_amount_24h", new String[] {"ML_HIGH_SPEND_24H", "High spend by the customer in the last 24 hours"});
        m.put("card_txn_count_1h", new String[] {"ML_CARD_VELOCITY_1H", "Many card transactions in the last hour"});
        m.put("device_txn_count_24h", new String[] {"ML_DEVICE_VELOCITY_24H", "Many transactions from the device in 24 hours"});
        m.put("new_payee", new String[] {"ML_NEW_PAYEE", "First payment to this beneficiary"});
        m.put("new_device_for_customer", new String[] {"ML_NEW_DEVICE", "Customer never used this device before"});
        m.put("new_country_for_customer", new String[] {"ML_NEW_COUNTRY", "First transaction with this country"});
        m.put("new_merchant_for_card", new String[] {"ML_NEW_MERCHANT", "First transaction of the card at this merchant"});
        m.put("amount_zscore", new String[] {"ML_UNUSUAL_AMOUNT", "Amount far above the customer's usual"});
        m.put("hour_deviation", new String[] {"ML_UNUSUAL_TIME", "Unusual time of day for the customer"});
        m.put("merchant_risk", new String[] {"ML_RISKY_MERCHANT", "Merchant with confirmed fraud"});
        m.put("beneficiary_age_days", new String[] {"ML_NEW_BENEFICIARY", "Beneficiary first seen recently"});
        m.put("txn_amount", new String[] {"ML_HIGH_AMOUNT", "High transaction amount"});
        m.put("customer_tenure_days", new String[] {"ML_NEW_CUSTOMER", "Customer has little history"});
        m.put("remote_access", new String[] {"ML_REMOTE_ACCESS", "Remote-access tool active"});
        m.put("device_emulator", new String[] {"ML_EMULATOR", "Device is an emulator"});
        return m;
    }

    static double sigmoid(double m) {
        return 1.0 / (1.0 + StrictMath.exp(-m));
    }

    static double round6(double v) {
        return Math.round(v * 1_000_000.0) / 1_000_000.0;
    }
}
